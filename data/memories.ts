export function getMemoryBySlug(slug: string): Memory | undefined {
  return memories.find((memory) => memory.slug === slug);
}

export function getMemoryNeighbors(slug: string) {
  const index = memories.findIndex((memory) => memory.slug === slug);
  if (index < 0) return null;

  return {
    currentIndex: index,
    previous: memories[(index - 1 + memories.length) % memories.length],
    next: memories[(index + 1) % memories.length],
  };
}
